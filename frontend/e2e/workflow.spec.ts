    await page.getByLabel('Password · 12 characters minimum').fill('Browser-test-2026!');
    await page.getByRole('button', { name: 'Create account', exact: true }).click();
    await page.getByRole('button', { name: 'Load bundled lab' }).click();
    await expect(page.getByRole('status')).toContainText('Bundled lab loaded');
    await page.getByRole('button', { name: 'Inventory', exact: true }).click();
